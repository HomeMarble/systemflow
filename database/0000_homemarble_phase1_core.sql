-- HomeMarble ERP — Phase 1 core schema (reconstructed for Lovable Cloud)
create extension if not exists pgcrypto;

create type public.app_role as enum ('admin','executive','sales','factory_manager','accountant');
create type public.order_status as enum ('design','measurement','awaiting_contract','manufacturing','ready_install','completed');
create type public.doc_kind as enum ('quote','contract','design','measurement','receipt','invoice','sample');
create type public.doc_status as enum ('draft','sent','approved','rejected','scheduled','done');

create table public.branches (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  city text,
  created_at timestamptz not null default now()
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  email text,
  branch_id uuid references public.branches(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.user_roles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  role public.app_role not null,
  created_at timestamptz not null default now(),
  unique (user_id, role)
);

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  phone text,
  email text,
  city text,
  address text,
  notes text,
  branch_id uuid references public.branches(id) on delete set null,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_no bigint generated by default as identity (start with 1001) unique,
  customer_id uuid not null references public.customers(id) on delete cascade,
  branch_id uuid references public.branches(id) on delete set null,
  work_type text not null default '',
  description text,
  total_value numeric not null default 0,
  required_deposit numeric not null default 0,
  status public.order_status not null default 'design',
  design_approved boolean not null default false,
  contract_approved boolean not null default false,
  sent_to_factory_at timestamptz,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.documents (
  id uuid primary key default gen_random_uuid(),
  doc_no bigint generated by default as identity (start with 1001) unique,
  kind public.doc_kind not null,
  customer_id uuid not null references public.customers(id) on delete cascade,
  order_id uuid references public.orders(id) on delete set null,
  title text not null default '',
  amount numeric not null default 0,
  status public.doc_status not null default 'draft',
  scheduled_date date,
  details text,
  items jsonb not null default '[]'::jsonb,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.audit_log (
  id uuid primary key default gen_random_uuid(),
  table_name text not null,
  action text not null,
  changes jsonb,
  user_id uuid,
  user_email text,
  created_at timestamptz not null default now()
);

grant select, insert, update, delete on public.branches, public.profiles, public.user_roles, public.customers, public.orders, public.documents to authenticated;
grant select, insert on public.audit_log to authenticated;
grant all on public.branches, public.profiles, public.user_roles, public.customers, public.orders, public.documents, public.audit_log to service_role;

