-- triggers
create or replace function public.hm_p1_touch() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
create trigger trg_p1_touch before update on public.customers for each row execute function public.hm_p1_touch();
create trigger trg_p1_touch before update on public.orders for each row execute function public.hm_p1_touch();
create trigger trg_p1_touch before update on public.documents for each row execute function public.hm_p1_touch();
create trigger trg_p1_touch before update on public.profiles for each row execute function public.hm_p1_touch();

create or replace function public.hm_p1_order_factory() returns trigger language plpgsql as $$
begin
  if new.status = 'manufacturing' and new.sent_to_factory_at is null then new.sent_to_factory_at := now(); end if;
  return new;
end $$;
create trigger trg_p1_order_factory before insert or update on public.orders for each row execute function public.hm_p1_order_factory();

create or replace function public.hm_p1_audit() returns trigger language plpgsql security definer set search_path = public as $$
declare ch jsonb; em text;
begin
  ch := case tg_op when 'UPDATE' then jsonb_build_object('old', to_jsonb(old), 'new', to_jsonb(new))
                   when 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  begin em := auth.jwt() ->> 'email'; exception when others then em := null; end;
  insert into public.audit_log (table_name, action, changes, user_id, user_email) values (tg_table_name, tg_op, ch, auth.uid(), em);
  return coalesce(new, old);
end $$;
create trigger trg_p1_audit after insert or update or delete on public.customers for each row execute function public.hm_p1_audit();
create trigger trg_p1_audit after insert or update or delete on public.orders for each row execute function public.hm_p1_audit();
create trigger trg_p1_audit after insert or update or delete on public.documents for each row execute function public.hm_p1_audit();
create trigger trg_p1_audit after insert or update or delete on public.user_roles for each row execute function public.hm_p1_audit();

-- new signup -> profile; first account becomes admin
create or replace function public.hm_handle_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name, email)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)), new.email)
  on conflict (id) do nothing;
  if not exists (select 1 from public.user_roles) then
    insert into public.user_roles (user_id, role) values (new.id, 'admin');
  end if;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.hm_handle_new_user();

