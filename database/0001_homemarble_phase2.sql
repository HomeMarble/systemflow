create or replace function public.hm_p2_audit()
returns trigger language plpgsql security definer set search_path = public as $$
declare ch jsonb; em text;
begin
  ch := case tg_op when 'UPDATE' then jsonb_build_object('old', to_jsonb(old), 'new', to_jsonb(new))
                   when 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  begin em := coalesce(auth.jwt() ->> 'email', null); exception when others then em := null; end;
  begin
    insert into public.audit_log (table_name, action, changes, user_id, user_email)
    values (tg_table_name, tg_op, ch, auth.uid(), em);
  exception when undefined_column then
    begin
      insert into public.audit_log (table_name, action, changes, user_email)
      values (tg_table_name, tg_op, ch, em);
    exception when others then null;
    end;
  when others then null;
  end;
  return coalesce(new, old);
end $$;

