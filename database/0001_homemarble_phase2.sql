create or replace function public.hm_receive_purchase(_id uuid, _lines jsonb)
returns text language plpgsql security definer set search_path = public as $$
declare pr record; _items jsonb; _ln jsonb; _i int; _q numeric; _it jsonb; all_done boolean := true; new_status text;
begin
  if not public.hm_has_any(array['admin','executive','factory_manager','purchasing','warehouse']) then
    raise exception 'لا تملك صلاحية استلام المشتريات';
  end if;
  select * into pr from public.purchase_requests where id = _id for update;
  if pr.id is null then raise exception 'طلب الشراء غير موجود'; end if;
  if pr.status not in ('approved','ordered','partial') then
    raise exception 'لا يمكن الاستلام إلا لطلب معتمد أو مُرسل للمورد';
  end if;
  _items := pr.items;
  for _ln in select * from jsonb_array_elements(coalesce(_lines, '[]'::jsonb)) loop
    _i := (_ln->>'i')::int; _q := coalesce((_ln->>'qty')::numeric, 0);
    if _q <= 0 then continue; end if;
    _it := _items -> _i;
    if _it is null then continue; end if;
    if _q > coalesce((_it->>'qty')::numeric,0) - coalesce((_it->>'received_qty')::numeric,0) then
      raise exception 'الكمية المستلمة للبند «%» أكبر من المتبقي', _it->>'name';
    end if;
    _items := jsonb_set(_items, array[_i::text, 'received_qty'], to_jsonb(coalesce((_it->>'received_qty')::numeric,0) + _q));
    if coalesce(_it->>'inventory_item_id','') <> '' then
      insert into public.inventory_movements (item_id, kind, qty, unit_cost, purchase_id, order_id, note)
      values ((_it->>'inventory_item_id')::uuid, 'in', _q, nullif(_it->>'unit_cost','')::numeric, pr.id, pr.order_id,
              'استلام طلب شراء #' || pr.pr_no);
    end if;
  end loop;
  for _it in select * from jsonb_array_elements(_items) loop
    if coalesce((_it->>'received_qty')::numeric,0) < coalesce((_it->>'qty')::numeric,0) then all_done := false; end if;
  end loop;
  new_status := case when all_done then 'received' else 'partial' end;
  perform set_config('hm.receiving', '1', true);
  update public.purchase_requests set items = _items, status = new_status where id = _id;
  perform set_config('hm.receiving', '', true);
  return new_status;
end $$;

create or replace function public.hm_consume_reservation(_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare r record;
begin
  if not public.hm_has_any(array['admin','executive','factory_manager','warehouse']) then
    raise exception 'لا تملك صلاحية صرف المواد';
  end if;
  select * into r from public.inventory_reservations where id = _id for update;
  if r.id is null or r.status <> 'active' then raise exception 'الحجز غير نشط'; end if;
  update public.inventory_reservations set status = 'consumed', consumed_at = now() where id = _id;
  insert into public.inventory_movements (item_id, kind, qty, order_id, reservation_id, note)
  values (r.item_id, 'out', r.qty, r.order_id, r.id, 'صرف مادة محجوزة للطلب');
end $$;

create or replace function public.hm_move_item(_id uuid, _stage text, _state text, _note text)
returns void language plpgsql security invoker set search_path = public as $$
begin
  perform set_config('hm.note', coalesce(_note, ''), true);
  update public.order_items
     set stage = coalesce(_stage, stage), stage_state = coalesce(_state, stage_state)
   where id = _id;
  if not found then raise exception 'البند غير موجود أو لا تملك صلاحية تعديله'; end if;
  perform set_config('hm.note', '', true);
end $$;

