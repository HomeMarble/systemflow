create or replace function public.hm_job_after()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if coalesce(current_setting('hm.restoring', true), '') = '1' then return coalesce(new, old); end if;
  if new.status = 'completed' and (tg_op = 'INSERT' or old.status <> 'completed') then
    perform set_config('hm.install', '1', true);
    perform set_config('hm.note', 'تم التركيب والتسليم — مهمة #' || new.job_no, true);
    update public.order_items set stage = 'installed' where order_id = new.order_id and stage = 'ready';
    perform set_config('hm.install', '', true);
    perform set_config('hm.note', '', true);
    begin update public.orders set status = 'completed' where id = new.order_id;
    exception when others then null; end;
  end if;
  return new;
end $$;
