create or replace function public.hm_movement_apply()
returns trigger language plpgsql security definer set search_path = public as $$
declare cur numeric;
begin
  if coalesce(current_setting('hm.restoring', true), '') = '1' then return coalesce(new, old); end if;
  if new.qty is null or new.qty = 0 then raise exception 'الكمية يجب ألا تكون صفراً'; end if;
  if new.kind in ('in','out') and new.qty < 0 then raise exception 'الكمية يجب أن تكون موجبة'; end if;
  select qty_on_hand into cur from public.inventory_items where id = new.item_id for update;
  if new.kind = 'out' and cur < new.qty then
    raise exception 'الكمية المطلوب صرفها (%) أكبر من الرصيد الحالي (%)', new.qty, cur;
  end if;
  if new.kind = 'adjust' and cur + new.qty < 0 then
    raise exception 'التسوية تجعل الرصيد بالسالب';
  end if;
  perform set_config('hm.mv', '1', true);
  update public.inventory_items
     set qty_on_hand = qty_on_hand + case new.kind when 'in' then new.qty when 'out' then -new.qty else new.qty end,
         unit_cost = case when new.kind = 'in' and coalesce(new.unit_cost,0) > 0 then new.unit_cost else unit_cost end,
         updated_at = now()
   where id = new.item_id;
  perform set_config('hm.mv', '', true);
  return new;
end $$;
drop trigger if exists trg_hm_movement_apply on public.inventory_movements;
create trigger trg_hm_movement_apply before insert on public.inventory_movements
  for each row execute function public.hm_movement_apply();

