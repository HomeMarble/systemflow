create or replace function public.hm_purchase_before()
returns trigger language plpgsql security definer set search_path = public as $$
declare tot numeric := 0; el jsonb;
begin
  if coalesce(current_setting('hm.restoring', true), '') = '1' then return coalesce(new, old); end if;
  if jsonb_typeof(new.items) <> 'array' then new.items := '[]'::jsonb; end if;
  for el in select * from jsonb_array_elements(new.items) loop
    tot := tot + coalesce((el->>'qty')::numeric, 0) * coalesce((el->>'unit_cost')::numeric, 0);
  end loop;
  new.total_cost := tot;
  if new.customer_id is null and new.order_id is not null then
    select customer_id into new.customer_id from public.orders where id = new.order_id;
  end if;
  if tg_op = 'UPDATE' and new.status is distinct from old.status then
    if new.status = 'approved' then
      if not public.hm_has_any(array['admin','executive','factory_manager','accountant']) then
        raise exception 'اعتماد طلب الشراء من صلاحية الإدارة أو مدير المصنع أو المحاسبة فقط';
      end if;
      new.approved_by := auth.uid(); new.approved_at := now();
    elsif new.status = 'ordered' then
      if old.status not in ('approved','ordered') then
        raise exception 'لا يمكن إرسال الطلب للمورد قبل اعتماده';
      end if;
      new.ordered_at := now();
    elsif new.status in ('partial','received') then
      if coalesce(current_setting('hm.receiving', true), '') <> '1' then
        raise exception 'يتم تسجيل الاستلام من خلال زر «استلام» فقط لتحديث المخزون';
      end if;
      if new.status = 'received' then new.received_at := now(); end if;
    end if;
  end if;
  return new;
end $$;
drop trigger if exists trg_hm_purchase_before on public.purchase_requests;
create trigger trg_hm_purchase_before before insert or update on public.purchase_requests
  for each row execute function public.hm_purchase_before();

create or replace function public.hm_item_before()
returns trigger language plpgsql security definer set search_path = public as $$
declare mgr boolean; ok boolean := false;
begin
  if coalesce(current_setting('hm.restoring', true), '') = '1' then return coalesce(new, old); end if;
  if tg_op = 'INSERT' then
    if new.stage in ('ready','installed') and coalesce(current_setting('hm.qc', true),'') <> '1' then
      raise exception 'لا يمكن إنشاء بند بحالة جاهز مباشرة';
    end if;
    return new;
  end if;

  mgr := public.hm_has_any(array['admin','executive','factory_manager']);

  if not mgr and coalesce(current_setting('hm.qc', true),'') <> '1' and coalesce(current_setting('hm.install', true),'') <> '1' then
    if (new.order_id, new.name, new.qty, coalesce(new.unit,''), coalesce(new.material,''), coalesce(new.dimensions,''), new.due_date, new.sort)
       is distinct from (old.order_id, old.name, old.qty, coalesce(old.unit,''), coalesce(old.material,''), coalesce(old.dimensions,''), old.due_date, old.sort) then
      raise exception 'تعديل بيانات البند من صلاحية مدير المصنع فقط';
    end if;
  end if;

  if new.stage is distinct from old.stage then
    new.stage_changed_at := now();
    if new.stage = 'ready' and coalesce(current_setting('hm.qc', true),'') <> '1' then
      raise exception 'لا يمكن اعتماد جاهزية المنتج إلا بعد اجتياز فحص الجودة والمعاينة';
    end if;
    if new.stage = 'installed' and (old.stage <> 'ready' or coalesce(current_setting('hm.install', true),'') <> '1') and not mgr then
      raise exception 'يتم تحويل البند إلى «تم التركيب» عند تسليم مهمة التركيب';
    end if;
    if new.stage = 'installed' and old.stage <> 'ready' then
      raise exception 'لا يُركّب إلا المنتج الجاهز المعتمد من الجودة';
    end if;
    if old.stage in ('ready','installed') and new.stage not in ('ready','installed') and not mgr then
      raise exception 'إرجاع منتج معتمد من صلاحية مدير المصنع فقط';
    end if;
    if not mgr and coalesce(current_setting('hm.qc', true),'') <> '1' and coalesce(current_setting('hm.install', true),'') <> '1' then
      if public.hm_has_any(array['cutting_supervisor']) and old.stage in ('queued','cutting') and new.stage in ('cutting','assembly') then ok := true; end if;
      if public.hm_has_any(array['assembly_supervisor']) and old.stage = 'assembly' and new.stage in ('assembly','polishing') then ok := true; end if;
      if public.hm_has_any(array['polishing_supervisor']) and old.stage = 'polishing' and new.stage in ('polishing','quality') then ok := true; end if;
      if not ok then raise exception 'لا تملك صلاحية نقل البند من هذه المرحلة'; end if;
    end if;
  elsif new.stage_state is distinct from old.stage_state and not mgr
        and coalesce(current_setting('hm.qc', true),'') <> '1' then
    if not ((public.hm_has_any(array['cutting_supervisor']) and old.stage in ('queued','cutting'))
         or (public.hm_has_any(array['assembly_supervisor']) and old.stage = 'assembly')
         or (public.hm_has_any(array['polishing_supervisor']) and old.stage = 'polishing')
         or (public.hm_has_any(array['quality_inspector']) and old.stage = 'quality')) then
      raise exception 'لا تملك صلاحية تحديث حالة هذه المرحلة';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists trg_hm_item_before on public.order_items;
create trigger trg_hm_item_before before insert or update on public.order_items
  for each row execute function public.hm_item_before();

create or replace function public.hm_sync_order(_order uuid)
returns void language plpgsql security definer set search_path = public as $$
declare total int; done int; st text;
begin
  select count(*), count(*) filter (where stage in ('ready','installed')) into total, done
    from public.order_items where order_id = _order;
  select status::text into st from public.orders where id = _order;
  if total > 0 and total = done and st = 'manufacturing' then
    begin update public.orders set status = 'ready_install' where id = _order;
    exception when others then null; end;
  end if;
end $$;

