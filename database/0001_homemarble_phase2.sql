create or replace function public.hm_available(_item uuid)
returns numeric language sql stable security definer set search_path = public as $$
  select coalesce((select qty_on_hand from public.inventory_items where id = _item), 0)
       - coalesce((select sum(qty) from public.inventory_reservations where item_id = _item and status = 'active'), 0);
$$;

create or replace function public.hm_reservation_check()
returns trigger language plpgsql security definer set search_path = public as $$
declare avail numeric;
begin
  if coalesce(current_setting('hm.restoring', true), '') = '1' then return coalesce(new, old); end if;
  if new.status = 'active' and (tg_op = 'INSERT' or old.status <> 'active' or new.qty > old.qty) then
    avail := public.hm_available(new.item_id) + case when tg_op = 'UPDATE' and old.status = 'active' then old.qty else 0 end;
    if new.qty > avail then
      raise exception 'لا يمكن الحجز: الكمية المتاحة فعلياً %', avail;
    end if;
  end if;
  if tg_op = 'UPDATE' and old.status <> 'active' and new.status <> old.status then
    raise exception 'لا يمكن تعديل حجز تم صرفه أو إلغاؤه';
  end if;
  return new;
end $$;
