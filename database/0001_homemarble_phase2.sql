     and (tg_op = 'INSERT' or old.status is distinct from new.status)
     and exists (select 1 from public.order_items oi
                  where oi.order_id = new.order_id and oi.stage not in ('ready','installed')) then
    raise exception 'لا يمكن بدء/إغلاق التركيب قبل اعتماد جاهزية جميع منتجات الطلب من فحص الجودة';
  end if;
  if new.status = 'in_progress' and new.started_at is null then new.started_at := now(); end if;
  if new.status = 'completed' then
    if coalesce(trim(new.handover_name), '') = '' then
      raise exception 'لا يمكن إغلاق التركيب قبل توثيق تسليم العميل (اسم المستلم)';
    end if;
    if coalesce(array_length(new.after_photos, 1), 0) = 0 then
      raise exception 'يجب رفع صورة واحدة على الأقل بعد التركيب قبل التسليم';
    end if;
    if new.handover_at is null then new.handover_at := now(); end if;
    if new.completed_at is null then new.completed_at := now(); end if;
  end if;
  return new;
end $$;
