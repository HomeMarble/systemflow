create or replace function public.hm_submit_password_request(_email text, _channel text, _contact text, _name text, _notes text)
returns bigint language plpgsql security definer set search_path = public as $$
declare n bigint; e text := lower(trim(coalesce(_email, '')));
begin
  if e !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'أدخل البريد الإلكتروني الصحيح للحساب'; end if;
  if coalesce(trim(_contact), '') = '' or char_length(_contact) > 120 then raise exception 'أدخل رقم الجوال أو البريد الذي سيتواصل معك عليه الدعم الفني'; end if;
  if _channel not in ('phone','whatsapp','email') then _channel := 'whatsapp'; end if;
  if (select count(*) from public.support_password_requests where lower(account_email) = e and created_at > now() - interval '1 hour') >= 3 then
    raise exception 'تم إرسال عدة طلبات لهذا البريد خلال الساعة الماضية — سيتواصل معك الدعم الفني قريباً';
  end if;
  if (select count(*) from public.support_password_requests where created_at > now() - interval '1 minute') >= 20 then
    raise exception 'ضغط كبير على الخدمة، حاول بعد دقيقة';
  end if;
  insert into public.support_password_requests (account_email, contact_channel, contact_value, full_name, notes)
  values (e, _channel, trim(_contact), nullif(trim(coalesce(_name, '')), ''), nullif(left(trim(coalesce(_notes, '')), 1000), ''))
  returning request_no into n;
  return n;
end $$;

create or replace function public.hm_visitor_open(_name text, _contact text, _subject text, _message text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare t public.support_threads;
begin
  if coalesce(trim(_name), '') = '' then raise exception 'اكتب اسمك'; end if;
  if coalesce(trim(_message), '') = '' then raise exception 'اكتب رسالتك'; end if;
  if (select count(*) from public.support_threads where created_at > now() - interval '1 minute') >= 30 then
    raise exception 'ضغط كبير على الخدمة، حاول بعد دقيقة';
  end if;
  insert into public.support_threads (visitor_name, visitor_contact, subject)
  values (left(trim(_name), 80), nullif(left(trim(coalesce(_contact, '')), 120), ''), nullif(left(trim(coalesce(_subject, '')), 150), ''))
  returning * into t;
  insert into public.support_messages (thread_id, sender, body) values (t.id, 'visitor', left(_message, 4000));
  return jsonb_build_object('thread_id', t.id, 'token', t.visitor_token, 'thread_no', t.thread_no);
end $$;

create or replace function public.hm_visitor_send(_thread uuid, _token uuid, _body text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from public.support_threads where id = _thread and visitor_token = _token) then
    raise exception 'المحادثة غير موجودة';
  end if;
  if coalesce(trim(_body), '') = '' then return; end if;
  if (select count(*) from public.support_messages where thread_id = _thread and sender = 'visitor' and created_at > now() - interval '1 minute') >= 20 then
    raise exception 'أرسلت رسائل كثيرة، انتظر قليلاً';
  end if;
  insert into public.support_messages (thread_id, sender, body) values (_thread, 'visitor', left(_body, 4000));
end $$;

create or replace function public.hm_visitor_fetch(_thread uuid, _token uuid, _after timestamptz)
returns jsonb language plpgsql security definer set search_path = public as $$
declare t public.support_threads; msgs jsonb;
begin
  select * into t from public.support_threads where id = _thread and visitor_token = _token;
  if t.id is null then raise exception 'المحادثة غير موجودة'; end if;
  select coalesce(jsonb_agg(jsonb_build_object('id', m.id, 'sender', m.sender, 'body', m.body, 'created_at', m.created_at,
           'staff_name', case when m.sender = 'staff' then coalesce((select split_part(coalesce(p.full_name, 'الدعم الفني'), ' ', 1) from public.profiles p where p.id = m.staff_id), 'الدعم الفني') end)
           order by m.created_at), '[]'::jsonb)
    into msgs
    from public.support_messages m
   where m.thread_id = _thread and (_after is null or m.created_at > _after);
  update public.support_threads set visitor_unread = 0 where id = _thread and visitor_unread > 0;
  return jsonb_build_object('status', t.status, 'thread_no', t.thread_no, 'messages', msgs);
end $$;

create or replace function public.hm_room_create(_title text, _hours int)
returns jsonb language plpgsql security definer set search_path = public as $$
declare c text; r public.chat_rooms; m uuid; tk uuid; nm text; alphabet text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789'; i int;
begin
  if not public.hm_is_mgr() then raise exception 'إنشاء الدردشات من صلاحية المدير أو المدير التنفيذي فقط'; end if;
  loop
    c := '';
    for i in 1..6 loop c := c || substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1); end loop;
    exit when not exists (select 1 from public.chat_rooms where code = c);
  end loop;
  insert into public.chat_rooms (code, title, expires_at)
  values (c, coalesce(nullif(trim(_title), ''), 'دردشة هوم ماربل'), case when coalesce(_hours, 0) > 0 then now() + make_interval(hours => _hours) end)
  returning * into r;
  select coalesce(full_name, email) into nm from public.profiles where id = auth.uid();
  insert into public.chat_members (room_id, display_name, user_id) values (r.id, coalesce(nm, 'الإدارة'), auth.uid()) returning id, token into m, tk;
  insert into public.chat_messages (room_id, sender_name, is_staff, body, user_id)
  values (r.id, 'النظام', true, 'تم إنشاء الدردشة — شارك الكود ' || c || ' مع من تريد', auth.uid());
  return jsonb_build_object('id', r.id, 'code', c, 'title', r.title, 'token', tk, 'member_id', m);
end $$;

create or replace function public.hm_room_join(_code text, _name text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r public.chat_rooms; m uuid; tk uuid; nm text;
begin
  select * into r from public.chat_rooms where code = upper(trim(coalesce(_code, '')));
  if r.id is null then raise exception 'الكود غير صحيح'; end if;
  if not r.is_active or (r.expires_at is not null and r.expires_at < now()) then raise exception 'هذه الدردشة مغلقة أو انتهت صلاحيتها'; end if;
  nm := nullif(left(trim(coalesce(_name, '')), 60), '');
  if nm is null and auth.uid() is not null then select coalesce(full_name, email) into nm from public.profiles where id = auth.uid(); end if;
  if nm is null then raise exception 'اكتب اسمك'; end if;
  if (select count(*) from public.chat_members where room_id = r.id and joined_at > now() - interval '1 minute') >= 60 then
    raise exception 'ضغط كبير على الدردشة، حاول بعد دقيقة';
  end if;
  insert into public.chat_members (room_id, display_name, user_id) values (r.id, nm, auth.uid()) returning id, token into m, tk;
  insert into public.chat_messages (room_id, sender_name, is_staff, body) values (r.id, 'النظام', true, nm || ' انضم إلى الدردشة');
  return jsonb_build_object('room_id', r.id, 'title', r.title, 'code', r.code, 'token', tk, 'member_id', m, 'name', nm);
end $$;

create or replace function public.hm_room_send(_room uuid, _token uuid, _body text)
returns void language plpgsql security definer set search_path = public as $$
declare mem public.chat_members; r public.chat_rooms; nm text;
begin
  select * into r from public.chat_rooms where id = _room;
  if r.id is null then raise exception 'الدردشة غير موجودة'; end if;
  if coalesce(trim(_body), '') = '' then return; end if;
  if _token is not null then select * into mem from public.chat_members where room_id = _room and token = _token; end if;
  if mem.id is null then
    if public.hm_is_mgr() then
      select coalesce(full_name, email) into nm from public.profiles where id = auth.uid();
      insert into public.chat_messages (room_id, sender_name, is_staff, body, user_id) values (_room, coalesce(nm, 'الإدارة'), true, left(_body, 4000), auth.uid());
      return;
    end if;
    raise exception 'لست عضواً في هذه الدردشة';
  end if;
  if not r.is_active or (r.expires_at is not null and r.expires_at < now()) then raise exception 'هذه الدردشة مغلقة'; end if;
  if (select count(*) from public.chat_messages where member_id = mem.id and created_at > now() - interval '1 minute') >= 30 then
    raise exception 'أرسلت رسائل كثيرة، انتظر قليلاً';
  end if;
  update public.chat_members set last_seen_at = now() where id = mem.id;
  insert into public.chat_messages (room_id, member_id, user_id, sender_name, is_staff, body)
  values (_room, mem.id, mem.user_id, mem.display_name, mem.user_id is not null and exists (select 1 from public.user_roles where user_id = mem.user_id), left(_body, 4000));
end $$;

create or replace function public.hm_room_fetch(_room uuid, _token uuid, _after timestamptz)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r public.chat_rooms; mem public.chat_members; msgs jsonb;
begin
  select * into r from public.chat_rooms where id = _room;
  if r.id is null then raise exception 'الدردشة غير موجودة'; end if;
  if _token is not null then select * into mem from public.chat_members where room_id = _room and token = _token; end if;
  if mem.id is null and not public.hm_is_mgr() then raise exception 'لست عضواً في هذه الدردشة'; end if;
  if mem.id is not null then update public.chat_members set last_seen_at = now() where id = mem.id; end if;
  select coalesce(jsonb_agg(jsonb_build_object('id', m.id, 'name', m.sender_name, 'body', m.body, 'created_at', m.created_at,
           'is_staff', m.is_staff, 'mine', (mem.id is not null and m.member_id = mem.id) or (mem.id is null and m.user_id = auth.uid() and m.member_id is null)) order by m.created_at), '[]'::jsonb)
    into msgs
    from public.chat_messages m where m.room_id = _room and (_after is null or m.created_at > _after);
  return jsonb_build_object('title', r.title, 'code', r.code,
    'active', r.is_active and (r.expires_at is null or r.expires_at > now()),
    'members', (select count(*) from public.chat_members where room_id = _room),
    'online', (select count(*) from public.chat_members where room_id = _room and last_seen_at > now() - interval '2 minutes'),
    'messages', msgs);
end $$;

