create or replace function public.hm__upsert_row(_table text, _row jsonb)
returns boolean language plpgsql security definer set search_path = public as $$
declare cols text; upd text;
begin
  select string_agg(quote_ident(c.column_name), ',' order by c.ordinal_position),
         string_agg(case when c.column_name <> 'id' then format('%1$I = excluded.%1$I', c.column_name) end, ',' order by c.ordinal_position)
    into cols, upd
    from information_schema.columns c
   where c.table_schema = 'public' and c.table_name = _table and c.is_generated = 'NEVER' and _row ? c.column_name;
  if cols is null or not (_row ? 'id') then return false; end if;
  execute format('insert into public.%I (%s) overriding system value select %s from jsonb_populate_record(null::public.%I, $1) on conflict (id) do %s',
                 _table, cols, cols, _table, case when upd is null then 'nothing' else 'update set ' || upd end)
    using _row;
  return true;
exception when others then
  return false;
end $$;
revoke all on function public.hm__upsert_row(text, jsonb) from public, anon, authenticated;

create or replace function public.hm__fix_identity(_table text)
returns void language plpgsql security definer set search_path = public as $$
declare c record; mx bigint;
begin
  for c in select column_name from information_schema.columns
            where table_schema = 'public' and table_name = _table and is_identity = 'YES' loop
    execute format('select coalesce(max(%I), 0) from public.%I', c.column_name, _table) into mx;
    perform setval(pg_get_serial_sequence('public.' || _table, c.column_name), mx + 1, false);
  end loop;
exception when others then null;
end $$;
revoke all on function public.hm__fix_identity(text) from public, anon, authenticated;

create or replace function public.hm_restore_rows(_table text, _rows jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r jsonb; ok int := 0; bad int := 0;
begin
  if not public.hm_is_mgr() then raise exception 'الاستعادة من صلاحية المدير أو المدير التنفيذي فقط'; end if;
  if not (_table = any(public.hm_backup_tables())) then raise exception 'جدول غير مسموح: %', _table; end if;
  if to_regclass('public.' || _table) is null then raise exception 'الجدول % غير موجود في قاعدة البيانات', _table; end if;
  if _table in ('profiles','user_roles','branches') and not public.hm_has_any(array['admin']) then
    raise exception 'استعادة المستخدمين والصلاحيات والفروع من صلاحية مدير النظام فقط';
  end if;
  if jsonb_typeof(_rows) <> 'array' then raise exception 'صيغة البيانات غير صحيحة'; end if;
  perform set_config('hm.restoring', '1', true);
  for r in select * from jsonb_array_elements(_rows) loop
    if public.hm__upsert_row(_table, r) then ok := ok + 1; else bad := bad + 1; end if;
  end loop;
  perform public.hm__fix_identity(_table);
  perform set_config('hm.restoring', '', true);
  return jsonb_build_object('table', _table, 'ok', ok, 'failed', bad);
end $$;

create or replace function public.hm_restore_deleted(_id uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare b bigint; t text; d record; ok int := 0; bad int := 0;
begin
  if not public.hm_is_mgr() then raise exception 'الاستعادة من صلاحية المدير أو المدير التنفيذي فقط'; end if;
  select batch into b from public.deleted_records where id = _id;
  if b is null then raise exception 'السجل غير موجود في سلة المحذوفات'; end if;
  perform set_config('hm.restoring', '1', true);
  foreach t in array public.hm_backup_tables() loop
    for d in select * from public.deleted_records where batch = b and table_name = t and restored_at is null order by deleted_at loop
      if public.hm__upsert_row(t, d.record) then
        ok := ok + 1;
        update public.deleted_records set restored_at = now(), restored_by = auth.uid() where id = d.id;
      else bad := bad + 1; end if;
    end loop;
    if exists (select 1 from public.deleted_records where batch = b and table_name = t) then perform public.hm__fix_identity(t); end if;
  end loop;
  perform set_config('hm.restoring', '', true);
  return jsonb_build_object('ok', ok, 'failed', bad);
end $$;

