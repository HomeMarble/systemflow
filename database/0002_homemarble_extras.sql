create or replace function public.hm_support_set_password(_email text, _password text, _request uuid)
returns void language plpgsql security definer set search_path = public, extensions, auth as $$
declare uid uuid; privileged boolean;
begin
  if not public.hm_is_support() then raise exception 'لا تملك صلاحية الدعم الفني'; end if;
  if char_length(coalesce(_password, '')) < 6 then raise exception 'كلمة المرور يجب ألا تقل عن 6 أحرف'; end if;
  select id into uid from auth.users where lower(email) = lower(trim(_email)) limit 1;
  if uid is null then raise exception 'لا يوجد حساب بهذا البريد'; end if;
  select exists (select 1 from public.user_roles where user_id = uid and role::text in ('admin','executive')) into privileged;
  if privileged and not public.hm_has_any(array['admin']) then
    raise exception 'تغيير كلمة مرور حساب إداري من صلاحية مدير النظام فقط';
  end if;
  update auth.users set encrypted_password = crypt(_password, gen_salt('bf')), updated_at = now() where id = uid;
  if _request is not null then
    update public.support_password_requests
       set status = 'in_progress', handled_by = auth.uid(), handled_at = now(),
           resolution = coalesce(resolution || E'\n', '') || 'تم تعيين كلمة مرور جديدة ' || to_char(now(), 'YYYY-MM-DD HH24:MI')
     where id = _request;
  end if;
  begin
    insert into public.audit_log (table_name, action, changes, user_id, user_email)
    values ('auth_password', 'UPDATE', jsonb_build_object('new', jsonb_build_object('title', 'تعيين كلمة مرور جديدة للحساب ' || lower(trim(_email)))), auth.uid(), auth.jwt() ->> 'email');
  exception when others then null;
  end;
end $$;

