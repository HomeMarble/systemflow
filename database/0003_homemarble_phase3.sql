create or replace function public.hm_coupon_upper()
returns trigger language plpgsql as $$
begin new.code := upper(regexp_replace(coalesce(new.code,''), '\s', '', 'g')); return new; end $$;
drop trigger if exists trg_hm_coupon_upper on public.coupons;
create trigger trg_hm_coupon_upper before insert or update on public.coupons for each row execute function public.hm_coupon_upper();

-- توليد كود عشوائي فريد
create or replace function public.hm_coupon_generate(_len int default 8)
returns text language plpgsql security definer set search_path = public as $$
declare c text; chars text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; i int;
begin
  if not public.hm_is_mgr() then raise exception 'توليد الكوبونات من صلاحية المدير والمدير التنفيذي فقط'; end if;
  loop
    c := 'HM';
    for i in 1..greatest(4, least(coalesce(_len, 8), 16)) loop
      c := c || substr(chars, 1 + floor(random() * length(chars))::int, 1);
    end loop;
    exit when not exists (select 1 from public.coupons where code = c);
  end loop;
  return c;
end $$;

-- معلومات الكوبون العامة للزائر (بدون بيانات داخلية)
create or replace function public.hm_coupon_public(_code text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare r public.coupons; ok boolean; pname text;
begin
  select * into r from public.coupons where code = upper(regexp_replace(coalesce(_code,''), '\s', '', 'g'));
  if not found then return jsonb_build_object('found', false); end if;
  ok := r.active and r.valid_from <= current_date and (r.valid_to is null or r.valid_to >= current_date)
        and (r.max_uses is null or r.used_count < r.max_uses);
  select name into pname from public.store_products where id = r.product_id;
  return jsonb_build_object('found', true, 'valid', ok, 'code', r.code, 'title', r.title,
    'discount_type', r.discount_type, 'discount_value', r.discount_value, 'scope', r.scope,
    'product_id', r.product_id, 'product_name', pname, 'category', r.category,
    'valid_from', r.valid_from, 'valid_to', r.valid_to,
    'whatsapp_number', r.whatsapp_number, 'contact_email', r.contact_email, 'auto_redirect', r.auto_redirect);
end $$;

-- كتالوج المتجر للزوار مع الكمية المتاحة فعلياً من المخزون
create or replace function public.hm_store_catalog()
returns table (id uuid, name text, category text, description text, price numeric, unit text, image_url text, available numeric, linked boolean)
language sql stable security definer set search_path = public as $$
  select p.id, p.name, p.category, p.description, p.price, p.unit, p.image_url,
         case when p.inventory_item_id is null then null
              else greatest(0, coalesce(i.qty_on_hand, 0) - coalesce((select sum(r.qty) from public.inventory_reservations r
                                                                      where r.item_id = i.id and r.status = 'active'), 0)) end,
         p.inventory_item_id is not null
    from public.store_products p
    left join public.inventory_items i on i.id = p.inventory_item_id
   where p.published
   order by p.category, p.name;
$$;

-- تسجيل طلب من المتجر (للزوار) — الأسعار والخصم تُحسب في قاعدة البيانات
create or replace function public.hm_store_place_order(_name text, _phone text, _email text, _city text, _address text,
                                                       _notes text, _items jsonb, _coupon text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare it jsonb; p record; q numeric; sub numeric := 0; disc numeric := 0; lines jsonb := '[]'::jsonb;
        c public.coupons; elig numeric := 0; no bigint; avail numeric;
begin
  if coalesce(trim(_name),'') = '' or coalesce(trim(_phone),'') = '' then raise exception 'الاسم ورقم الجوال مطلوبان'; end if;
  if jsonb_typeof(_items) <> 'array' or jsonb_array_length(_items) = 0 then raise exception 'السلة فارغة'; end if;
  if jsonb_array_length(_items) > 50 then raise exception 'عدد كبير من الأصناف'; end if;
  if (select count(*) from public.store_orders where phone = trim(_phone) and created_at > now() - interval '1 hour') >= 5 then
    raise exception 'تم تجاوز الحد المسموح من الطلبات، حاول لاحقاً';
  end if;
  if coalesce(trim(_coupon),'') <> '' then
    select * into c from public.coupons where code = upper(regexp_replace(_coupon, '\s', '', 'g')) for update;
    if not found or not (c.active and c.valid_from <= current_date and (c.valid_to is null or c.valid_to >= current_date)
                         and (c.max_uses is null or c.used_count < c.max_uses)) then
      raise exception 'الكوبون غير صالح أو منتهي الصلاحية';
    end if;
  end if;
  for it in select * from jsonb_array_elements(_items) loop
    select sp.*, (select greatest(0, coalesce(i.qty_on_hand,0) - coalesce((select sum(r.qty) from public.inventory_reservations r where r.item_id = i.id and r.status='active'),0))
                    from public.inventory_items i where i.id = sp.inventory_item_id) as av
      into p from public.store_products sp where sp.id = (it ->> 'id')::uuid and sp.published;
    if not found then raise exception 'منتج غير متاح'; end if;
    q := greatest(1, least(coalesce((it ->> 'qty')::numeric, 1), 1000));
    if p.inventory_item_id is not null and coalesce(p.av, 0) < q then raise exception 'الكمية المطلوبة من "%" غير متاحة حالياً', p.name; end if;
    sub := sub + q * p.price;
    if c.id is not null and (c.scope = 'all' or (c.scope = 'product' and c.product_id = p.id) or (c.scope = 'category' and c.category = p.category)) then
      elig := elig + q * p.price;
    end if;
    lines := lines || jsonb_build_object('id', p.id, 'name', p.name, 'category', p.category, 'qty', q, 'price', p.price, 'total', q * p.price);
  end loop;
  if c.id is not null then
    if elig = 0 then raise exception 'الكوبون لا ينطبق على المنتجات المختارة'; end if;
    disc := case when c.discount_type = 'percent' then round(elig * c.discount_value / 100, 2) else least(c.discount_value, elig) end;
    update public.coupons set used_count = used_count + 1 where id = c.id;
  end if;
  insert into public.store_orders (customer_name, phone, email, city, address, notes, items, subtotal, discount, total, coupon_code)
  values (trim(_name), trim(_phone), nullif(trim(_email),''), nullif(trim(_city),''), nullif(trim(_address),''), nullif(trim(_notes),''),
          lines, sub, disc, sub - disc, c.code)
  returning order_no into no;
  return jsonb_build_object('order_no', no, 'subtotal', sub, 'discount', disc, 'total', sub - disc);
end $$;

